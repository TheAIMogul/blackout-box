// Regenerates src/foodkeeper-data.ts from data/foodkeeper.json (USDA FSIS FoodKeeper, CC0).
// Usage: node scripts/build-foodkeeper.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const here = (p) => fileURLToPath(new URL(p, import.meta.url))
const raw = JSON.parse(readFileSync(here('../../../data/foodkeeper.json'), 'utf8'))
const flat = (row) => Object.assign({}, ...row)
const sheet = (name) => raw.sheets.find((s) => s.name === name).data.map(flat)

const range = (p, pre) => {
  const min = p[`${pre}_Min`] ?? null
  const max = p[`${pre}_Max`] ?? null
  const metric = p[`${pre}_Metric`] ?? null
  return min == null && max == null && metric == null ? null : [min, max, metric]
}
const first = (p, ...pres) => pres.map((pre) => range(p, pre)).find(Boolean) ?? null

const rows = sheet('Product').map((p) => [
  p.ID, p.Category_ID, p.Name, p.Name_subtitle ?? null, p.Keywords ?? '',
  first(p, 'Refrigerate', 'DOP_Refrigerate', 'Refrigerate_After_Opening'),
  first(p, 'Freeze', 'DOP_Freeze'),
])
const version = sheet('Version').find((v) => v.Current_Version === 'Yes') ?? {}

const out = `// GENERATED by scripts/build-foodkeeper.mjs from data/foodkeeper.json. Do not edit.
// USDA FSIS FoodKeeper (CC0 1.0), ${raw.fileName}, version ${version.Data_Version_Number}, modified ${version.Modified_Date}.
// Row: [ID, Category_ID, Name, Name_subtitle, Keywords, fridge [min, max, metric], freezer [min, max, metric]]
export type FkRange = [number | null, number | null, string | null] | null
export type FkRow = [number, number, string, string | null, string, FkRange, FkRange]
export const FK_VERSION = ${JSON.stringify({ file: raw.fileName, version: version.Data_Version_Number, modified: version.Modified_Date })}
export const FK_ROWS: FkRow[] = [
${rows.map((r) => '  ' + JSON.stringify(r) + ',').join('\n')}
]
`
writeFileSync(here('../src/foodkeeper-data.ts'), out)
console.log(`wrote ${rows.length} rows, ${out.length} chars`)
